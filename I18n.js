function pick(locale) {
  var l = String(locale || "").toLowerCase()
  for (var code in TABLES) if (l.indexOf(code) === 0) return code
  return "en"
}

function tr(lang, text, args) {
  var table = TABLES[lang]
  var s = table && table[text] !== undefined ? table[text] : text
  for (var i = 0; i < (args || []).length; i++) s = s.split("%" + (i + 1)).join(String(args[i]))
  return s
}
